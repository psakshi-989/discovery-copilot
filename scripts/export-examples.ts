/**
 * Turns saved eval results into the example runs shown on the website.
 * Usage: npm run export-examples [folder-with-result-json-files]
 * Picks the first scored run of each case, so the examples are real scored output, not hand-edited.
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "eval/results";
const out = "src/data/examples";
const TITLES: Record<string, string> = {
  "streaming-ops": "Streaming service content operations",
  "creator-marketplace": "Creator marketplace payouts",
  "design-templates": "Design template marketplace review",
  "design-template": "Design template marketplace review",
  "insurance-claims": "Insurance claims triage",
};
const slug = (s: string) => s.replace(/_/g, "-");

if (!existsSync(dir)) throw new Error(`Folder not found: ${dir}`);
mkdirSync(out, { recursive: true });

const seen = new Set<string>();
const written: string[] = [];

for (const file of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
  const data = JSON.parse(readFileSync(join(dir, file), "utf8"));
  for (const run of data.runs ?? []) {
    const id = slug(String(run.case ?? ""));
    if (!id || seen.has(id) || !run.result) continue;
    const transcriptPath = [`eval/cases/${run.case}.txt`, `eval/cases/${id}.txt`, `samples/${id}.txt`].find(existsSync);
    if (!transcriptPath) {
      console.warn(`skip ${id}: transcript not found`);
      continue;
    }
    const score = run.score ?? run.scores ?? {};
    const recall = score.weightedRecall ?? null;
    const view = {
      id,
      title: TITLES[id] ?? id,
      createdAt: new Date().toISOString(),
      transcript: readFileSync(transcriptPath, "utf8").trim(),
      result: run.result,
      evalBadge: recall === null ? undefined : { weightedRecall: recall, flagRecall: score.flagRecall ?? null },
      isExample: true,
    };
    writeFileSync(join(out, `${id}.json`), JSON.stringify(view, null, 1));
    seen.add(id);
    written.push(id);
  }
}

if (written.length === 0) throw new Error(`No usable runs found in ${dir}`);
const names = written.map((id) => ({ id, v: id.replace(/-(\w)/g, (_, c: string) => c.toUpperCase()) }));
const index = [
  "// Generated by `npm run export-examples`. Safe to edit by hand, but the script overwrites it.",
  'import type { RunView } from "../../lib/runView";',
  ...names.map((n) => `import ${n.v} from "./${n.id}.json";`),
  "",
  `export const examples = [${names.map((n) => n.v).join(", ")}] as unknown as RunView[];`,
  "",
].join("\n");
writeFileSync(join(out, "index.ts"), index);
console.log(`Wrote ${written.length} example(s): ${written.join(", ")}`);
